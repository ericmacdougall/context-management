"""Judge of one unittest step of the live chain (review 42cfd11 R3). Standard library only; reads files, prints one word.

  judge  <expected-file> <unittest -v output> <exit status>   prints pass | red | fail(<why>) | green | red-without-signature(<why>)
  sign   <unittest -v output> <step> <source note>             prints an expected file for a red step from that output
  oom    "<before>" "<after>"                                    ok, or fail(...) when a store's oom_kill grew or is unreadable

The expected file pins, one per line ('#' comments):
  STEP <name>               the step it is for
  DECLARED pass|red         the declared outcome
  RAN <n>                   "Ran <n> tests" must be printed (a crash or a lost module changes it)
  SKIP <n>                  exactly <n> tests skipped (default 0: a skip fails the step unless declared)
  <FAIL|ERROR> <test> :: <text>   red only: this test fails with this kind, and <text> appears in its traceback
A pass step must exit 0, print OK and fail nothing. A red step must exit non-zero, and its failing blocks must be exactly
the listed ones with their kinds and texts; any other FAIL or ERROR block, including one outside a test method
(setUpClass, tearDownClass, setUpModule, a module that did not import), is extra. Hex runs of 8 or more characters are
compared as '#' on both sides (event ids, uuids)."""
import re
import sys

HEX = re.compile(r"[0-9a-f]{8,}")


def norm(s):
    return HEX.sub("#", s)


def blocks(text):
    """{(kind, name): traceback text} for every "FAIL: x (...)" / "ERROR: x (...)" block of a unittest -v run."""
    out, cur, buf = {}, None, []
    for ln in text.splitlines():
        m = re.match(r"^(FAIL|ERROR): (\S+)", ln)
        if m or ln.startswith("Ran ") or (cur and re.match(r"^={20,}$", ln)):
            if cur:
                out[cur] = "\n".join(buf)
            cur, buf = ((m.group(1), m.group(2)) if m else None), []
            continue
        if cur:
            buf.append(ln)
    if cur:
        out[cur] = "\n".join(buf)
    return out


def read_spec(path):
    spec = {"STEP": None, "DECLARED": None, "RAN": None, "SKIP": 0, "entries": {}, "bad": []}
    for ln in open(path, encoding="utf-8"):
        ln = ln.rstrip("\n")
        if not ln.strip() or ln.startswith("#"):
            continue
        k = ln.split(" ", 1)[0]
        if k in ("STEP", "DECLARED"):
            spec[k] = ln.split(" ", 1)[1].strip()
        elif k in ("RAN", "SKIP"):
            spec[k] = int(ln.split(" ", 1)[1])
        elif k in ("FAIL", "ERROR") and " :: " in ln:
            name, text = ln.split(" ", 1)[1].split(" :: ", 1)
            if not text.strip():
                spec["bad"].append(ln)
            spec["entries"][(k, name.strip())] = norm(text.strip())
        else:
            spec["bad"].append(ln)
    return spec


def judge(spec_path, out_path, status):
    try:
        spec = read_spec(spec_path)
    except OSError:
        return "fail(no expected file)"
    if spec["bad"] or spec["RAN"] is None or spec["DECLARED"] not in ("pass", "red"):
        return "fail(expected file invalid)"
    try:
        text = open(out_path, encoding="utf-8", errors="replace").read()
    except OSError:
        return "fail(no output)"
    ran = re.findall(r"^Ran (\d+) tests? in ", text, re.M)
    skipped = re.findall(r"skipped=(\d+)", text.splitlines()[-1] if text.strip() else "")
    n_skip = int(skipped[0]) if skipped else 0
    if not ran:
        return "fail(no Ran line)"
    if int(ran[-1]) != spec["RAN"]:
        return f"fail(Ran {ran[-1]}, expected {spec['RAN']})"
    if n_skip != spec["SKIP"]:
        return f"fail(skipped {n_skip}, expected {spec['SKIP']})"
    got = blocks(text)
    if spec["DECLARED"] == "pass":
        if status != 0 or got or not re.search(r"^OK\b", text, re.M):
            return f"fail(exit={status} failing={len(got)})"
        return "pass"
    if status == 0:
        return "green"
    if not spec["entries"]:
        return "fail(expected file invalid)"
    want = spec["entries"]
    missing = [k for k in want if k not in got]
    extra = [k for k in got if k not in want]
    wrong = [k for k in want if k in got and want[k] not in norm(got[k])]
    if missing or extra or wrong:
        return f"red-without-signature(missing {len(missing)} extra {len(extra)} wrong-text {len(wrong)})"
    return "red"


def sign(out_path, step, note):
    text = open(out_path, encoding="utf-8", errors="replace").read()
    ran = re.findall(r"^Ran (\d+) tests? in ", text, re.M)
    last = text.splitlines()[-1] if text.strip() else ""
    skipped = re.findall(r"skipped=(\d+)", last)
    print(f"# {step} declared red; generated by step_judge.py sign from {note}. Each line: kind, test, and a text that")
    print("# must appear in its traceback (the exception's last line). Review 42cfd11 R3.")
    print(f"STEP {step}\nDECLARED red\nRAN {ran[-1] if ran else '?'}\nSKIP {skipped[0] if skipped else 0}")
    for (kind, name), tb in sorted(blocks(text).items(), key=lambda x: x[0][1]):
        exc = [ln for ln in tb.splitlines() if re.match(r"^(?:[a-z_]\w*\.)*[A-Z][a-z]\w*(: |$)", ln)]   # a raised class
        line = (exc[-1] if exc else tb.strip().splitlines()[-1]).strip()
        print(f"{kind} {name} :: {norm(line)[:160]}")


def oom(before, after):
    """before / after: "name=id:count ..." or "name=unreadable" per store (live_chain.sh oomk). ok when every store's
    count is readable after the step and did not grow (a recreated container, new id, must still be at 0)."""
    def parse(s):
        out = {}
        for tok in s.split():
            name, _, v = tok.partition("=")
            cid, _, n = v.rpartition(":")
            out[name] = (cid, int(n)) if v != "unreadable" and n.isdigit() and cid else None
        return out
    b, a = parse(before), parse(after)
    if not a:
        return "fail(oom_kill unreadable)"
    for name, v in sorted(a.items()):
        if v is None:
            return f"fail(oom_kill unreadable {name})"
        base = b[name][1] if b.get(name) and b[name][0] == v[0] else 0
        if v[1] > base:
            return f"fail(oom_kill {name} {base}->{v[1]})"
    return "ok"


if __name__ == "__main__":
    if sys.argv[1:2] == ["judge"] and len(sys.argv) == 5:
        print(judge(sys.argv[2], sys.argv[3], int(sys.argv[4])))
    elif sys.argv[1:2] == ["oom"] and len(sys.argv) == 4:
        print(oom(sys.argv[2], sys.argv[3]))
    elif sys.argv[1:2] == ["sign"] and len(sys.argv) == 5:
        sign(sys.argv[2], sys.argv[3], sys.argv[4])
    else:
        raise SystemExit(__doc__)
