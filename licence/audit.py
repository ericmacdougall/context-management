"""Write licence/CLAUSE-AUDIT.md (review 13): one section per clause of clauses.CLAUSES, its registered words split into conjuncts, the
code that establishes each conjunct from raw rows (file:line), the raw-row input that violates it alone (tests.test_clauses.VIOLATIONS)
and its state on the committed lives (results/summary_current.json). Generated, never edited by hand; tests.test_clauses checks that
the committed file equals what this writes.
Usage: cd licence && python3 audit.py CLAUSE-AUDIT.md"""
import collections
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.dirname(HERE))
import clauses  # noqa: E402
import verdicts  # noqa: E402


def _lines(f):
    with open(os.path.join(HERE, f)) as fh:
        return fh.read().split("\n")


def def_line(ref):
    """'file.py:function' -> 'file.py:<line of its def or class>'."""
    f, name = ref.split(":")
    for i, l in enumerate(_lines(f)):
        s = l.lstrip()
        if s.startswith("def %s(" % name) or s.startswith("class %s(" % name):
            return "%s:%d" % (f, i + 1)
    raise KeyError(ref)


def verdict_line(cid):
    """verdicts.py line that decides a conjunct: its first mention (inside the gate's verdict function), or judge_parts for a LIMIT."""
    if any(c.cid == cid and c.kind == "LIMIT" for c in clauses.CLAUSES):
        return def_line("verdicts.py:judge_parts")
    for i, l in enumerate(_lines("verdicts.py")):
        if '"%s"' % cid in l:
            return "verdicts.py:%d" % (i + 1)
    raise KeyError(cid)


def states(cur):
    """{conjunct: Counter(state)} over every inventory life of each gate that decides it."""
    out = collections.defaultdict(collections.Counter)
    for life, gates in cur["lives"].items():
        for g, v in gates.items():
            for cid, st in (v.get("conjuncts") or {}).items():
                out[cid][st] += 1
    return out


def overall(counter):
    if counter.get("VIOLATED"):
        return "VIOLATED"
    if counter.get("NOT_ESTABLISHED") or not counter:
        return "NOT_ESTABLISHED"
    return "ESTABLISHED"


def render(cur_path=os.path.join(HERE, "results", "summary_current.json")):
    from tests.test_clauses import HALVES, VIOLATIONS
    with open(cur_path) as fh:
        cur = json.load(fh)
    st = states(cur)
    lines_t = _lines("THRESHOLDS.md")
    conj_all = sorted(clauses.CONJUNCTS)
    per = {c: overall(st[c]) for c in conj_all}
    tot = collections.Counter(per.values())
    clause_st = collections.Counter(v["status"] for v in cur["clauses"].values())
    rows_total = sum(len(c.conj) for c in clauses.CLAUSES)
    out = ["# Clause audit (generated by `python3 audit.py CLAUSE-AUDIT.md`; do not edit)", "",
           "Review 13 of GoodQA #16096. Every clause of `clauses.CLAUSES` (THRESHOLDS.md, cited line by line) is split into the separate "
           "conditions (conjuncts) its registered words impose. A conjunct is decided by one place in `verdicts.py`, from a figure that one "
           "recorder function computes from raw rows (`results/<life>.rows.gz`, `.poll.gz`, `.oracle.gz`, `.writes.gz`) or from a primary "
           "matrix cell. It is ESTABLISHED, VIOLATED or NOT_ESTABLISHED; a gate is PASS only when every conjunct of it is ESTABLISHED, and a "
           "clause only when every conjunct of every gate deciding it is ESTABLISHED on every life of the campaign inventory. A clause is "
           "FAIL only when one of its own conjuncts is VIOLATED. Figures with no raw record (the EXP3 migration figures, `exp2.writes` and "
           "EXP2-T1 for lives without saved oracle legs) are withheld when a conjunct is established (`summarize.gate_view`): they can never make a PASS, and a failure they record still "
           "makes the gate FAIL (`summarize.judged`).", "",
           "Each conjunct has a test (`tests.test_clauses.ConjunctViolationTests`) that changes the RAW record of a passing base (committed "
           "down_7 or up_1 rows, poll and oracle; a synthetic write record) so that only that conjunct stops being established, runs it "
           "through parse, reduction (`summarize.rebuild`) and the verdict, and asserts the gate and every clause citing the conjunct are "
           "not PASS. A conjunct whose registered words are an AND of several conditions has one more input per further condition "
           "(`half`, `tests.test_clauses.HALVES`). `also` lists a conjunct the same raw change cannot avoid moving; `whole` marks a conjunct the evidence type enforces "
           "(its violation leaves the evidence unparsed); `figure` marks the cases with no raw record.", "",
           "## Totals on the committed lives", "",
           "- Clauses: %d (%s)." % (len(clauses.CLAUSES), ", ".join("%s %d" % (k, clause_st[k]) for k in ("PASS", "FAIL", "UNVERIFIED"))),
           "- Distinct conjuncts: %d (%s), of which %d are LIMIT conjuncts that are never established. Clause-to-conjunct citations: %d."
           % (len(conj_all), ", ".join("%s %d" % (k, tot[k]) for k in ("ESTABLISHED", "VIOLATED", "NOT_ESTABLISHED")),
              sum(1 for c in clauses.CLAUSES if c.kind == "LIMIT"), rows_total),
           "- Ungated clauses (REPORTED or RULE): %d; every one is UNVERIFIED (no conjunct is established by a gate)."
           % sum(1 for c in clauses.CLAUSES if not c.conj), "",
           "A conjunct is counted ESTABLISHED here only if it is established on every inventory life of its gates; per-life counts are in "
           "each table.", ""]
    for c in clauses.CLAUSES:
        s = cur["clauses"][c.cid]["status"]
        out += ["## %s (%s, THRESHOLDS.md:%d): %s" % (c.cid, c.kind, c.line, s), "",
                "> %s" % c.quote, "", "Full registered line: `%s`" % lines_t[c.line - 1].strip().replace("`", "'"), ""]
        if not c.conj:
            out += ["Gates: none. Conjunct: NOT ESTABLISHED (%s). Adversarial input: none needed; the clause is UNVERIFIED whatever the "
                    "data (`tests.test_clauses.ClauseTableTests.test_current_summary_reports_every_clause_with_a_status`)."
                    % ("reported only" if c.kind == "REPORTED" else "a procedure or recording rule"), ""]
            if c.note:
                out += ["Note: %s" % c.note, ""]
            continue
        out += ["Gates: %s." % ", ".join(c.gates), "",
                "| conjunct | registered words | established by | adversarial raw input | committed lives |", "|---|---|---|---|---|"]
        for cid in c.conj:
            d = clauses.CONJUNCTS[cid]
            if any(x.cid == cid and x.kind == "LIMIT" for x in clauses.CLAUSES):
                how, test = "NOT ESTABLISHED (LIMIT): %s" % d.note, "none: never established (`test_every_conjunct_has_one_raw_violation_and_every_limit_is_never_established`)"
            else:
                how = "%s; %s%s" % (def_line(d.recorder), verdict_line(cid), (" (%s)" % d.note) if d.note else "")
                vs = [("", VIOLATIONS[cid])] + [("half %s: " % k.split("#")[1], h) for k, h in sorted(HALVES.items()) if k.split("#")[0] == cid]
                test = "<br>".join("%s%s%s" % (lab, v.doc, (" [%s]" % "; ".join(fl)) if fl else "") for lab, v in vs for fl in [
                    [f for f, on in (("whole", v.whole), ("figure", v.level == "figure")) if on] + (["also " + ", ".join(v.also)] if v.also else [])])
            n = st[cid]
            lives = ", ".join("%s %d" % (k, n[k]) for k in ("ESTABLISHED", "VIOLATED", "NOT_ESTABLISHED") if n[k]) or "no life"
            out.append("| `%s` | THRESHOLDS.md:%d \"%s\" | %s | %s | %s |" % (cid, d.line, d.quote.replace("|", "\\|"), how.replace("|", "\\|"),
                                                                          test.replace("|", "\\|"), lives))
        out += ["", "Status reason: %s" % cur["clauses"][c.cid]["reason"].replace("\n", " "), ""]
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    text = render()
    with open(sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "CLAUSE-AUDIT.md"), "w") as fh:
        fh.write(text)
